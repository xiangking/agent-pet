export function t(locale, key, params) {
  const dict = locales[locale] || locales.en
  let text = dict[key] ?? locales.en[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, v)
    }
  }
  return text
}
